    fn new_doc(&mut self) {
        let mut d = Doc { elements: vec![], wires: vec![], nid: 1 };
        let mut tmp = Editor::new();
        tmp.doc = std::mem::take(&mut d);
        let el = tmp.new_element("SIMCTRL", 22.0, -10.0, 0, false);
        tmp.doc.elements.push(el);
        self.ed.set_doc(tmp.doc);
        self.file = None;
        self.file_name = "未命名電路".into();
        self.doc_layout = None;
        // the previous circuit's viewers stay open with their own results
        self.doc_serial += 1;
        self.bode = BodeView::new();
        self.msgs.clear();
        self.canvas.err_els.clear();
        self.canvas.want_fit = true;
        self.canvas.scale = 20.0;
    }
    fn load_text(&mut self, txt: &str, name: String, path: Option<PathBuf>) -> Result<(), String> {
        let (doc, screens) = Doc::from_json(txt)?;
        self.ed.set_doc(doc);
        self.file_stamp = path.as_deref().and_then(file_stamp_of);
        self.ext_change = false;
        self.file = path;
        self.file_name = name;
        self.doc_layout = screens;
        // the previous circuit's viewers stay open with their own results
        self.doc_serial += 1;
        self.bode = BodeView::new();
        self.msgs.clear();
        self.canvas.err_els.clear();
        self.canvas.want_fit = true;
        Ok(())
    }
    /// reload the open circuit when its file changed on disk (an AI agent saved it through the MCP server)
    fn watch_file(&mut self, ctx: &egui::Context) {
        let Some(p) = self.file.clone() else { return };
        ctx.request_repaint_after(std::time::Duration::from_millis(1000));
        let now = ctx.input(|i| i.time);
        if now - self.stamp_at < 0.8 || self.ext_change {
            return;
        }
        self.stamp_at = now;
        let st = file_stamp_of(&p);
        if st.is_none() || st == self.file_stamp {
            return;
        }
        if self.ed.dirty && !self.ed.doc.elements.is_empty() {
            self.ext_change = true;
        } else {
            self.reload_external(&p);
        }
    }
    fn reload_external(&mut self, p: &std::path::Path) {
        let st = file_stamp_of(p);
        let r = std::fs::read_to_string(p).map_err(|e| e.to_string()).and_then(|t| Doc::from_json(&t));
        match r {
            Ok((doc, screens)) => {
                // the same circuit: the view and the waveform viewer stay; Ctrl+Z restores the version before
                self.ed.set_doc(doc);
                if screens.is_some() {
                    self.doc_layout = screens;
                }
                self.file_stamp = st;
                self.ext_change = false;
                self.canvas.err_els.clear();
                self.toast("電路檔已在外部修改（例如 AI 代理），已重新載入；Ctrl+Z 可復原");
            }
            // half written or not a circuit file (yet): try again on the next check
            Err(_) => {
                self.ext_change = false;
            }
        }
    }
    pub fn open_path(&mut self, p: PathBuf) {
        let ext = p.extension().map(|e| e.to_string_lossy().to_lowercase()).unwrap_or_default();
        if ext == crate::wave::WAVE_EXT {
            self.open_wave(&p);
            return;
        }
        if ext == "psimsch" || ext == "sch" {
            self.show_msgs("無法開啟檔案", vec![Msg { err: true, text: format!("無法直接開啟 PSIM 原生電路檔（{}）：.psimsch 是 PSIM 的專有格式，沒有公開規格。請在 PSIM 以「Simulate → Generate Netlist File (XML)」匯出 XML 網表。", p.display()), els: vec![] }]);
            return;
        }
        match std::fs::read_to_string(&p) {
            Ok(txt) => {
                let name = p.file_stem().map(|s| s.to_string_lossy().to_string()).unwrap_or_else(|| "電路".into());
                match self.load_text(&txt, name, Some(p.clone())) {
                    Ok(()) => self.add_recent(p),
                    Err(e) => self.show_msgs("無法開啟檔案", vec![Msg { err: true, text: format!("無法開啟檔案：{}", e), els: vec![] }]),
                }
            }
            Err(e) => self.show_msgs("無法開啟檔案", vec![Msg { err: true, text: format!("無法讀取 {}：{}", p.display(), e), els: vec![] }]),
        }
    }
    /// a saved waveform file into the waveform viewer (the circuit stays as it is)
    fn open_wave(&mut self, p: &std::path::Path) {
        // a waveform file always gets a viewer of its own (not tied to the circuit in the editor)
        let i = self.new_wave(0);
        match self.waves[i].load_wave(p) {
            Ok(()) => {
                self.waves[i].open = true;
                self.waves[i].report_msg = format!("已開啟波形檔：{}", p.display());
                self.wave_last = self.waves[i].uid;
            }
            Err(e) => {
                self.waves.remove(i);
                self.show_msgs("無法開啟波形檔", vec![Msg { err: true, text: format!("無法開啟波形檔：{}", e), els: vec![] }]);
            }
        }
    }
    /// a new waveform viewer with the user's colours and settings
    fn new_wave(&mut self, doc: u64) -> usize {
        let mut w = WaveView::new();
        w.colors = self.wave_colors.clone();
        w.style = self.wave_style;
        self.wave_uid += 1;
        w.uid = self.wave_uid;
        w.doc = doc;
        self.waves.push(w);
        self.waves.len() - 1
    }
    /// the viewer of the circuit in the editor
    fn doc_wave(&self) -> Option<usize> {
        self.waves.iter().position(|w| w.doc == self.doc_serial)
    }
    fn has_doc_wave(&self) -> bool {
        self.doc_wave().map(|i| self.waves[i].res.is_some()).unwrap_or(false)
    }
    fn open_doc_wave(&mut self) -> bool {
        match self.doc_wave().filter(|&i| self.waves[i].res.is_some()) {
            Some(i) => {
                self.waves[i].open = true;
                true
            }
            None => false,
        }
    }
