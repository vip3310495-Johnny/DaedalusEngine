    /// write an embedded document to %TEMP%\DaedalusEngine and open it with its associated program
    fn open_temp_doc(&mut self, name: &str, bytes: &[u8], what: &str, viewer: &str) {
        let dir = std::env::temp_dir().join("DaedalusEngine");
        let p = dir.join(name);
        let r = std::fs::create_dir_all(&dir).and_then(|_| std::fs::write(&p, bytes));
        match r {
            Ok(()) => {
                #[cfg(windows)]
                let opened = std::process::Command::new("explorer.exe").arg(&p).spawn();
                #[cfg(not(windows))]
                let opened = std::process::Command::new("xdg-open").arg(&p).spawn();
                match opened {
                    Ok(_) => self.toast(format!("已在{}開啟{}", viewer, what)),
                    Err(e) => self.toast(format!("無法開啟{}（{}）；檔案位置：{}", viewer, e, p.display())),
                }
            }
            Err(e) => self.toast(format!("無法寫入{}（{}）", what, e)),
        }
    }
    fn add_recent(&mut self, p: PathBuf) {
        self.recent.retain(|q| q != &p);
        self.recent.insert(0, p);
        self.recent.truncate(10);
    }
    fn save(&mut self, save_as: bool) -> bool {
        let path = if save_as || self.file.is_none() {
            match rfd::FileDialog::new().add_filter("電路檔", &["psimx"]).set_file_name(format!("{}.psimx", self.file_name)).save_file() {
                Some(p) => p,
                None => return false,
            }
        } else {
            self.file.clone().unwrap()
        };
        let screens = self.doc_wave().and_then(|i| self.waves[i].layout_names()).or_else(|| self.doc_layout.clone());
        let txt = self.ed.doc.to_json(daedalus_core::VERSION, screens);
        match std::fs::write(&path, txt) {
            Ok(()) => {
                self.file_name = path.file_stem().map(|s| s.to_string_lossy().to_string()).unwrap_or_default();
                self.file = Some(path.clone());
                self.file_stamp = file_stamp_of(&path);
                self.ext_change = false;
                self.ed.dirty = false;
                self.add_recent(path);
                self.toast("已儲存");
                true
            }
            Err(e) => {
                self.show_msgs("無法儲存", vec![Msg { err: true, text: format!("無法寫入檔案：{}", e), els: vec![] }]);
                false
            }
        }
    }
    fn request(&mut self, p: Pending) {
        if self.ed.dirty && !self.ed.doc.elements.is_empty() {
            self.pending = Some(p);
        } else {
            self.do_pending(p);
        }
    }
    fn do_pending(&mut self, p: Pending) {
        match p {
            Pending::New => self.new_doc(),
            Pending::Open(None) => {
                if let Some(p) = rfd::FileDialog::new().add_filter("電路檔", &["psimx", "json"]).add_filter("波形檔", &[crate::wave::WAVE_EXT]).add_filter("所有檔案", &["*"]).pick_file() {
                    self.open_path(p);
                }
            }
            Pending::Open(Some(p)) => self.open_path(p),
            Pending::Example(i) => {
                let ex = &EXAMPLES[i];
                let _ = self.load_text(ex.json, ex.name.into(), None);
                self.ed.dirty = false;
            }
            Pending::Exit => {
                self.allow_close = true;
            }
        }
    }

