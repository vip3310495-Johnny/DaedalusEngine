    /// unpinned library: a tab on the left edge; the library slides out over the schematic while the pointer is
    /// on the tab or the library, and hides again shortly after it leaves (or once an element is picked)
    fn lib_autohide(&mut self, ui: &mut Ui, ctx: &egui::Context, pal: &Pal) {
        let now = ctx.input(|i| i.time);
        let open = self.lib_fly.is_some();
        let strip = egui::Panel::left("lib_strip").exact_size(28.0).resizable(false).show(ui, |ui| {
            let r = ui.available_rect_before_wrap();
            let tab = egui::Rect::from_min_size(r.min + vec2(2.0, 10.0), vec2(r.width() - 4.0, 92.0));
            let resp = ui.interact(tab, ui.scope_id().with("lib_tab"), egui::Sense::click());
            let hot = resp.hovered() || open;
            let vis = ui.visuals();
            ui.painter().rect_filled(tab, 5.0, if hot { pal.accent_soft } else { vis.widgets.inactive.weak_bg_fill });
            ui.painter().rect_stroke(tab, 5.0, egui::Stroke::new(1.0, if hot { pal.accent } else { vis.widgets.noninteractive.bg_stroke.color }), egui::StrokeKind::Inside);
            let col = if hot { pal.accent } else { vis.text_color() };
            for (k, ch) in "元件庫".chars().enumerate() {
                ui.painter().text(egui::pos2(tab.center().x, tab.min.y + 18.0 + 24.0 * k as f32), egui::Align2::CENTER_CENTER, ch, egui::FontId::proportional(14.0), col);
            }
            resp.on_hover_text("元件庫（自動隱藏）")
        });
        let tab = strip.inner;
        let strip_rect = strip.response.rect;
        if tab.hovered() || tab.clicked() {
            self.lib_fly = Some(now);
        }
        if self.script.is_some() {
            self.dbg_rects.push(("lib_tab".into(), tab.rect));
        }
        let Some(t_in) = self.lib_fly else { return };
        let w = 300.0;
        let mut picked = None;
        let fly_id = ui.scope_id().with("lib_fly");
        let area = egui::Area::new(fly_id).order(egui::Order::Foreground).fixed_pos(strip_rect.right_top()).show(ctx, |ui| {
            egui::Frame::side_top_panel(ui.style()).shadow(ui.style().visuals.popup_shadow).show(ui, |ui| {
                ui.set_width(w);
                ui.set_height((strip_rect.height() - 12.0).max(200.0));
                self.lib_header(ui);
                picked = self.lib.ui(ui, &mut self.syms, pal);
            });
        });
        let fly = area.response.rect;
        if self.script.is_some() {
            self.dbg_rects.push(("lib_fly".into(), fly));
        }
        if let Some(t) = picked {
            self.lib_fly = None;
            self.start_place(&t);
            return;
        }
        if !self.lib_open || self.settings.lib_pinned {
            return;
        }
        let ptr = ctx.input(|i| i.pointer.hover_pos());
        let inside = ptr.map(|p| fly.expand(8.0).contains(p) || strip_rect.contains(p)).unwrap_or(false);
        let busy = self.lib.search_focus || ctx.input(|i| i.pointer.any_down()) && inside;
        if inside || busy {
            self.lib_fly = Some(now);
        } else if now - t_in > 0.45 {
            self.lib_fly = None;
        } else {
            ctx.request_repaint_after(std::time::Duration::from_millis(60));
        }
    }
